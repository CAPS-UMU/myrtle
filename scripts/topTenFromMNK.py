# Given matmul input dimensions M,N,K, this program queries myrtle for the search space 
# specified by `suffix`` (top 10 in L1 usage by default)
# then generates the scripts to compile, run, and extract results for that search space.

# Usage: python topTenFromMNK.py path-to-inputSize.txt outputFolder suffix
# when suffix is not provided, the search space defaults to sorted and pruned for top 10 in L1 usage
# when suffix is "all", the full searchspace is used (sorted in the dataframe by L1 usage)
# when suffix is anything else, this program tries to use the search space 
# generated by myrtle with the provided suffix. 

def gen_slurm_scripts(outputFolder,topLevelOutputFolder):
    # echo job
    slurmScript = open(f"./{outputFolder}/echo-job.slurm", "w")
    slurmScript.writelines("#!/bin/bash\n")
    slurmScript.writelines("#SBATCH --job-name=" + topLevelOutputFolder + "\n")
    slurmScript.writelines("#SBATCH --output=" + f"{topLevelOutputFolder}-stdout-sbatch.txt" + "\n")
    slurmScript.writelines("#SBATCH --error=" + f"{topLevelOutputFolder}-stderr-sbatch.txt"  + "\n")
    slurmScript.writelines("#SBATCH --nodes=1\n")
    slurmScript.writelines("#SBATCH --ntasks-per-node=1\n")
    slurmScript.writelines("#SBATCH --cpus-per-task=1\n")
    slurmScript.writelines("#SBATCH --mem=2G\n")
    print("# -------------------------------",file=slurmScript)
    print("# SETTINGS ----------------------",file=slurmScript)
    print("# -------------------------------",file=slurmScript)
    print("# This script was autogenerated by topTenFromMNK.py script inside the myrtle repo.",file=slurmScript)
    print("bash check.sh",file=slurmScript)
    print("#bash compile.sh",file=slurmScript)
    print("#bash run.sh",file=slurmScript)
    print("#bash extract.sh",file=slurmScript)
    slurmScript.close()
